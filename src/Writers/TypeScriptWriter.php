<?php

namespace ApiTypes\Writers;

use ApiTypes\Data\Endpoint;
use ApiTypes\Data\ResponseDefinition;
use ApiTypes\Support\EnumRegistry;
use ApiTypes\Support\ResourceTypeBuilder;
use ApiTypes\Support\Ts;
use ApiTypes\Support\TypeMapper;
use Illuminate\Http\Resources\Json\JsonResource;

class TypeScriptWriter
{
    private const WRAPPERS = ['ResourceResponse', 'CollectionResponse', 'PaginatedResponse',
        'SimplePaginatedResponse', 'CursorPaginatedResponse', 'RawPaginator'];

    private const HEADER = "// This file is auto-generated by laravel-api-types.\n"
        ."// Do not edit manually — run `php artisan api-types:generate` instead.\n\n";

    public function __construct(
        private readonly TypeMapper $mapper,
        private readonly ResourceTypeBuilder $resources,
        private readonly EnumRegistry $enums,
        private readonly string $enumStyle = 'enum',
    ) {}

    /**
     * @param  Endpoint[]  $endpoints
     * @param  array<string, class-string<\UnitEnum>>  $enums  discovered enums (TS name => class)
     * @return array<string, string>  file name => contents
     */
    public function write(array $endpoints, array $enums): array
    {
        usort($endpoints, fn (Endpoint $a, Endpoint $b) => strcmp($a->key, $b->key));

        // Order matters: each step registers enums/resources that later steps render.
        [$requests, $requestNames] = $this->renderRequests($endpoints);
        $endpointsTs = $this->renderEndpoints($endpoints, $requestNames);
        $resourcesTs = $this->renderResources();

        $enums = array_merge($enums, $this->mapper->usedEnums, $this->enums->all());
        ksort($enums);

        return [
            'enums.ts' => $this->renderEnums($enums),
            'requests.ts' => $requests,
            'resources.ts' => $resourcesTs,
            'endpoints.ts' => $endpointsTs,
            'index.ts' => self::HEADER."export * from './enums';\nexport * from './requests';\n"
                ."export * from './resources';\nexport * from './endpoints';\n",
        ];
    }

    private function renderEnums(array $enums): string
    {
        $blocks = [];

        foreach ($enums as $name => $class) {
            $blocks[] = $this->renderEnum($name, $class);
        }

        return self::HEADER.($blocks === [] ? "export {};\n" : implode("\n\n", $blocks)."\n");
    }

    private function renderEnum(string $name, string $class): string
    {
        $cases = array_map(
            fn (\UnitEnum $case) => [$case->name, Ts::literal($case)],
            $class::cases(),
        );

        if ($this->enumStyle === 'union') {
            $values = array_column($cases, 1);

            return "export type {$name} = ".($values === [] ? 'never' : implode(' | ', $values)).';';
        }

        if ($this->enumStyle === 'const') {
            $lines = array_map(fn ($c) => '  '.Ts::key($c[0]).': '.$c[1].',', $cases);

            return "export const {$name} = {\n".implode("\n", $lines)."\n} as const;\n\n"
                ."export type {$name} = (typeof {$name})[keyof typeof {$name}];";
        }

        $lines = array_map(fn ($c) => '  '.Ts::key($c[0]).' = '.$c[1].',', $cases);

        return "export enum {$name} {\n".implode("\n", $lines)."\n}";
    }

    /** @return array{0: string, 1: array<class-string, string>} */
    private function renderRequests(array $endpoints): array
    {
        $names = [];
        $blocks = [];

        foreach ($endpoints as $endpoint) {
            $class = $endpoint->requestClass;

            if ($class === null || isset($names[$class])) {
                continue;
            }

            $name = $this->uniqueName(class_basename($class), $names);
            $names[$class] = $name;
            $type = $this->mapper->objectType($endpoint->rules);

            $blocks[] = str_starts_with($type, '{')
                ? "export interface {$name} {$type}"
                : "export type {$name} = {$type};";
        }

        $body = $blocks === [] ? "export {};\n" : implode("\n\n", $blocks)."\n";
        $imports = $this->imports($body, array_keys($this->mapper->usedEnums), './enums');

        return [self::HEADER.($imports ? $imports."\n" : '').$body, $names];
    }

    /** @param  array<class-string, string>  $requestNames */
    private function renderEndpoints(array $endpoints, array $requestNames): string
    {
        $types = [];
        $consts = [];

        foreach ($endpoints as $endpoint) {
            $key = Ts::literal($endpoint->key);
            $request = $endpoint->requestClass ? $requestNames[$endpoint->requestClass] : null;
            $methods = array_map([Ts::class, 'literal'], $endpoint->methods);
            $readOnly = $endpoint->isReadOnly();

            $types[] = "  {$key}: {";
            $types[] = '    method: '.implode(' | ', $methods).';';
            $types[] = '    params: '.$this->paramsType($endpoint->uriParams).';';
            $types[] = '    query: '.($readOnly && $request ? $request : 'Record<string, unknown>').';';
            $types[] = '    body: '.($readOnly ? 'never' : ($request ?? 'unknown')).';';
            $types[] = '    response: '.str_replace("\n", "\n    ", $this->responseType($endpoint->response)).';';
            $types[] = '  };';

            $consts[] = "  {$key}: { methods: [".implode(', ', $methods).'], uri: '
                .Ts::literal('/'.ltrim($endpoint->uri, '/')).' },';
        }

        $body = $this->join($types);
        $imports = $this->imports($body, array_values($requestNames), './requests')
            .$this->imports($body, array_merge(self::WRAPPERS, $this->resources->names()), './resources');

        return self::HEADER.($imports ? $imports."\n" : '').<<<TS
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'OPTIONS';

export interface Endpoints {
{$body}}

export type EndpointName = keyof Endpoints;
export type EndpointParams<N extends EndpointName> = Endpoints[N]['params'];
export type EndpointQuery<N extends EndpointName> = Endpoints[N]['query'];
export type EndpointBody<N extends EndpointName> = Endpoints[N]['body'];
export type EndpointResponse<N extends EndpointName> = Endpoints[N]['response'];

export const endpoints = {
{$this->join($consts)}} as const satisfies Record<EndpointName, { methods: readonly HttpMethod[]; uri: string }>;

/**
 * Builds a URL for a named endpoint:  url('users.show', { user: 5 }) -> '/api/users/5'
 */
export function url<N extends EndpointName>(
  name: N,
  ...args: EndpointParams<N> extends Record<string, never> ? [] : [params: EndpointParams<N>]
): string {
  const params = (args[0] ?? {}) as Record<string, string | number | undefined>;

  const path = endpoints[name].uri.replace(/\{(\w+)\??\}/g, (_, key: string) => {
    const value = params[key];
    return value === undefined ? '' : encodeURIComponent(String(value));
  });

  return path.replace(/\/+$/, '') || '/';
}

TS;
    }

    private function responseType(?ResponseDefinition $response): string
    {
        if ($response === null) {
            return 'unknown';
        }

        if ($response->kind === ResponseDefinition::RESOURCE) {
            $name = $this->resources->resource($response->type);

            return match ($response->pagination) {
                'length' => "PaginatedResponse<{$name}>",
                'simple' => "SimplePaginatedResponse<{$name}>",
                'cursor' => "CursorPaginatedResponse<{$name}>",
                default => $response->collection ? "CollectionResponse<{$name}>" : "ResourceResponse<{$name}>",
            };
        }

        $type = $response->kind === ResponseDefinition::MODEL
            ? $this->resources->model($response->type)
            : $response->type;

        return match (true) {
            $response->pagination !== null => "RawPaginator<{$type}>",
            $response->collection => Ts::arrayOf($type),
            default => $type,
        };
    }

    private function renderResources(): string
    {
        $blocks = $this->resources->render();
        $body = $this->wrappers()."\n\n".($blocks === [] ? '' : implode("\n\n", $blocks)."\n");
        $imports = $this->imports($body, array_keys($this->enums->all()), './enums');

        return self::HEADER.($imports ? $imports."\n" : '').$body;
    }

    /** Response envelopes produced by Laravel's JsonResource / paginators. */
    private function wrappers(): string
    {
        $wrap = class_exists(JsonResource::class) ? JsonResource::$wrap : 'data';
        $key = Ts::key($wrap ?? 'data');

        $single = $wrap === null ? 'T' : "{ {$key}: T }";
        $collection = $wrap === null ? 'T[]' : "{ {$key}: T[] }";

        return <<<TS
export type ResourceResponse<T> = {$single};
export type CollectionResponse<T> = {$collection};

export interface PaginationLinks {
  first: string | null;
  last: string | null;
  prev: string | null;
  next: string | null;
}

export interface PaginatorLink {
  url: string | null;
  label: string;
  active: boolean;
}

/** Resource::collection(\$query->paginate()) */
export interface PaginatedResponse<T> {
  {$key}: T[];
  links: PaginationLinks;
  meta: {
    current_page: number;
    from: number | null;
    last_page: number;
    links: PaginatorLink[];
    path: string;
    per_page: number;
    to: number | null;
    total: number;
  };
}

/** Resource::collection(\$query->simplePaginate()) */
export interface SimplePaginatedResponse<T> {
  {$key}: T[];
  links: PaginationLinks;
  meta: { current_page: number; from: number | null; path: string; per_page: number; to: number | null };
}

/** Resource::collection(\$query->cursorPaginate()) */
export interface CursorPaginatedResponse<T> {
  {$key}: T[];
  links: PaginationLinks;
  meta: { path: string; per_page: number; next_cursor: string | null; prev_cursor: string | null };
}

/** A paginator returned directly, without a resource: return User::paginate(); */
export interface RawPaginator<T> {
  current_page: number;
  data: T[];
  first_page_url: string;
  from: number | null;
  last_page: number;
  last_page_url: string;
  links: PaginatorLink[];
  next_page_url: string | null;
  path: string;
  per_page: number;
  prev_page_url: string | null;
  to: number | null;
  total: number;
}
TS;
    }

    /** `import type { ... }` for every name that actually appears in $body. */
    private function imports(string $body, array $names, string $from): string
    {
        $used = array_values(array_unique(array_filter(
            $names,
            fn ($name) => preg_match('/(?<![\w$])'.preg_quote($name, '/').'(?![\w$])/', $body),
        )));
        sort($used);

        return $used === [] ? '' : 'import type { '.implode(', ', $used)." } from '{$from}';\n";
    }

    /** @param  array<string, bool>  $params */
    private function paramsType(array $params): string
    {
        if ($params === []) {
            return 'Record<string, never>';
        }

        $parts = [];
        foreach ($params as $name => $optional) {
            $parts[] = Ts::key($name).($optional ? '?' : '').': string | number';
        }

        return '{ '.implode('; ', $parts).' }';
    }

    private function join(array $lines): string
    {
        return $lines === [] ? '' : implode("\n", $lines)."\n";
    }

    private function uniqueName(string $base, array $taken): string
    {
        $name = $base;
        $i = 2;

        while (in_array($name, $taken, true)) {
            $name = $base.$i++;
        }

        return $name;
    }
}
